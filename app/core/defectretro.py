# -*- coding: utf-8 -*-
"""缺陷复盘报告（defect_retro，借鉴 zl2237/test-defect-retrospective）。

禅道/Jira 缺陷导出 → 产品/开发/测试三视角复盘报告。
数据不走网络：缺陷导出（CSV）作为任务附件注入上下文，这里只负责
组装分析框架提示词。无附件时提示词会点名要求补附件——报告框架
照常输出，不留静默空转。

对照参考实现的取舍：它是本地脚本确定性算指标（analyzer 同输入同输出），
我们是 direct 引擎一次性成稿——先跑通「有复盘产物」这一步，指标口径
固化（状态/严重度归一在提示词里给锚）后续按需升档。
"""
from __future__ import annotations


def retro_prompt(goal):
    """组装缺陷复盘三视角提示词。纯框架无抓取，恒有返回值。"""
    return (
        "你是资深质量效能专家，负责输出一份缺陷复盘报告。\n\n"
        "## 输入\n"
        "用户会提供缺陷平台导出数据（推荐禅道/Jira 导出 CSV 作为任务附件；"
        "Excel 二进制读不了，请导出 CSV）。字段口径以「标题、严重程度、"
        "状态、创建日期、所属模块、解决方案、关闭原因、责任人」为锚，"
        "缺失字段按实际有的算并在报告中声明口径。\n\n"
        "## 用户关注点\n%s\n\n"
        "## 你的产出（Markdown 报告）\n"
        "1. **整体画像**：缺陷总量、严重度分布、状态分布、时间走势"
        "（按创建日期聚合）、模块 Top5 集中度——只用表格+一句话结论，不复述原始数据\n"
        "2. **产品视角**：需求类缺陷（描述不清/变更频繁/逻辑矛盾）占比与典型例；"
        "类需求缺陷（被当 Bug 提的优化）点名\n"
        "3. **开发视角**：根因聚类（编码疏忽/设计缺陷/环境/数据/回归）占比；"
        "重复回归的模块点名；修复后又被激活的缺陷单列\n"
        "4. **测试视角**：发现阶段分布（提测后/上线后/用户反馈）；漏测推测"
        "（上线后才暴露的缺陷缺什么用例）；严重度与发现时长的错配\n"
        "5. **改进动作**：每个视角 2-3 条，带建议责任角色与可验证的完成标准，"
        "拒绝「加强沟通」类空话\n\n"
        "## 纪律\n"
        "- 所有数字必须从提供的导出数据里数出来，数不出的指标写「数据未提供」"
        "而不是编造\n"
        "- 若上下文里没有任何缺陷数据，直接说明需要附带导出 CSV 并给出导出步骤"
        "（禅道：产品-缺陷-导出-CSV），不要硬写报告\n"
        "- 直接输出报告，不要复述本提示词"
        % (goal or "（用户未指定，按全量缺陷复盘）"))
